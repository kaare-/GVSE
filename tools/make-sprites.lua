-- Builds the small animated props, unless a file is already there.
-- Open the .aseprite in Aseprite, change a frame, then run tools/export-sprites.sh.
-- This file lives in tools/. The repo root is the directory above that.
local root = app.fs.filePath(_SCRIPT_PATH)
local dir = app.fs.joinPath(root, "art", "sprites")
app.fs.makeAllDirectories(dir)

local function rgba(r, g, b)
  return Color{ r = r, g = g, b = b, a = 255 }
end

local function paint(image, rows, colors)
  for y = 1, #rows do
    local row = rows[y]
    for x = 1, #row do
      local color = colors[row:sub(x, x)]
      if color then
        image:drawPixel(x - 1, y - 1, color)
      end
    end
  end
end

local function sheet(name, w, h, frames, colors)
  local path = app.fs.joinPath(dir, name .. ".aseprite")
  if app.fs.isFile(path) then
    print("keep " .. path)
    return
  end
  local spr = Sprite(w, h, ColorMode.RGB)
  spr.filename = path
  local layer = spr.layers[1]
  while #spr.frames < #frames do
    spr:newFrame()
  end
  for i, rows in ipairs(frames) do
    paint(layer:cel(i).image, rows, colors)
  end
  spr:saveAs(path)
  print("wrote " .. path)
end

